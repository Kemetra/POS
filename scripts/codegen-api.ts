/**
 * T052 / RT-869 — OpenAPI → TypeScript types codegen runner.
 *
 * Generates `src/shared/api-types.ts` ONLY from the Backend-Core contract set
 * vendored under `contracts/backend-core/openapi/**`: exactly the files listed
 * in `contracts/backend-core/PIN`, the same set the RT-217 contract-conformance
 * suite pins. There is no other source (no legacy snapshot, no live fetch);
 * refresh the contracts with `npm run contracts:repin`, then re-run this.
 *
 * The contracts are separate documents whose component names collide with
 * different bodies (each declares its own `Error`, `DecimalAmount`, …), so they
 * cannot be merged into one document. Each file becomes one type-only
 * namespace named after its path, e.g. `pos-payments/vouchers.yaml` →
 * `PosPaymentsVouchers.components['schemas']['PosValidateVoucherRequest']`.
 *
 * Determinism contract (T051):
 *   - Same contract set → byte-identical output across runs.
 *   - Output uses LF line endings only (no CR), even on Windows.
 *   - Every option is pinned explicitly so a future contributor cannot
 *     regenerate with different defaults and silently trip
 *     `verify-codegen`.
 *   - Header sentinel ("AUTOGENERATED — DO NOT EDIT") is part of the
 *     committed bytes; reading the first line tells humans not to edit.
 *
 * CLI:
 *   tsx scripts/codegen-api.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import jsYaml from 'js-yaml';
import openapiTS, { astToString, type OpenAPITSOptions } from 'openapi-typescript';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');

export const DEFAULT_CONTRACTS_DIR = path.join(REPO_ROOT, 'contracts', 'backend-core');
export const DEFAULT_OUT_PATH = path.join(REPO_ROOT, 'src', 'shared', 'api-types.ts');

const loadYaml = (jsYaml as { load: (src: string) => unknown }).load;

const HEADER = [
  '// AUTOGENERATED — DO NOT EDIT.',
  '// This file is the output of `npm run codegen:api`, which derives types only',
  '// from the Backend-Core contracts vendored under contracts/backend-core/openapi',
  '// (the files listed in contracts/backend-core/PIN). One namespace per contract',
  '// file. To refresh, run `npm run contracts:repin`, then `npm run codegen:api`.',
  '',
  '',
].join('\n');

/**
 * Pinned `openapi-typescript` options. Every option that affects output
 * shape is set explicitly. Default-tracking via "// uses lib default" is
 * deliberately avoided — the lib's defaults can change minor-version, and
 * silent default drift would defeat the verify gate.
 */
const FIXED_OPTIONS: OpenAPITSOptions = {
  additionalProperties: false,
  alphabetize: true, // sort keys alphabetically — pure determinism guard
  arrayLength: false,
  emptyObjectsUnknown: false,
  defaultNonNullable: true,
  excludeDeprecated: false,
  immutable: false,
  silent: true,
  exportType: false,
  enum: false,
  enumValues: false,
  conditionalEnums: false,
  dedupeEnums: false,
  pathParamsAsTypes: false,
  propertiesRequiredByDefault: false,
  rootTypes: false,
  rootTypesNoSchemaPrefix: false,
  rootTypesKeepCasing: false,
  makePathsEnum: false,
  generatePathParams: false,
  readWriteMarkers: false,
};

export interface GenerateApiTypesOptions {
  /** The vendored contract root holding `PIN` and `openapi/`. */
  contractsDir: string;
  /** Where to write the generated .ts file. */
  outPath: string;
}

/** The contract files listed in `PIN`, relative to `openapi/`, in PIN order. */
export function readPinnedContractFiles(contractsDir: string): string[] {
  const pin = readFileSync(path.join(contractsDir, 'PIN'), 'utf8');
  const files = pin
    .split('\n')
    .map((line) => /^file: (\S+) [0-9a-f]{40}$/.exec(line.trim())?.[1])
    .filter((file): file is string => file !== undefined);
  if (files.length === 0) throw new Error(`[codegen-api] no contract files listed in PIN`);
  return files;
}

/** `pos-payments/vouchers.yaml` → `PosPaymentsVouchers`. */
export function namespaceFor(file: string): string {
  return file
    .replace(/(\.openapi)?\.ya?ml$/, '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

/**
 * The contracts declare OpenAPI 3.1 but some schemas use the 3.0 keyword
 * `nullable: true`, which openapi-typescript ignores under 3.1. Rewrite it to
 * the 3.1 form `type: [T, 'null']` so the generated type is `T | null`, as the
 * contract intends. Pure — returns a new tree.
 */
export function normalizeNullable(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(normalizeNullable);
  if (!isRecord(node)) return node;
  const entries = Object.entries(node)
    .filter(([k]) => k !== 'nullable')
    .map(([k, v]): [string, unknown] => [k, normalizeNullable(v)]);
  const out: Record<string, unknown> = Object.fromEntries(entries);
  if (node.nullable === true && typeof out.type === 'string') out.type = [out.type, 'null'];
  return out;
}

async function generateNamespace(contractsDir: string, file: string): Promise<string> {
  const doc = normalizeNullable(
    loadYaml(readFileSync(path.join(contractsDir, 'openapi', file), 'utf8')),
  ) as Parameters<typeof openapiTS>[0];
  const body = astToString(await openapiTS(doc, FIXED_OPTIONS)).replace(/\r\n/g, '\n');
  const indented = body
    .trimEnd()
    .split('\n')
    .map((line) => (line.length > 0 ? `    ${line}` : line))
    .join('\n');
  return `/** Generated from contracts/backend-core/openapi/${file}. */\nexport namespace ${namespaceFor(file)} {\n${indented}\n}\n`;
}

/**
 * Generate TypeScript types from the vendored contract set and write the
 * deterministic, header-prefixed result to `outPath`. Returns the generated text.
 */
export async function generateApiTypes(options: GenerateApiTypesOptions): Promise<string> {
  const files = readPinnedContractFiles(options.contractsDir);
  const namespaces: string[] = [];
  for (const file of files) namespaces.push(await generateNamespace(options.contractsDir, file));
  const finalText = HEADER + namespaces.join('\n');

  writeFileSync(options.outPath, finalText, { encoding: 'utf8' });
  return finalText;
}

async function main(): Promise<void> {
  console.log(
    `[codegen-api] generating ${path.relative(REPO_ROOT, DEFAULT_OUT_PATH)} from ${path.relative(REPO_ROOT, DEFAULT_CONTRACTS_DIR)}`,
  );
  await generateApiTypes({ contractsDir: DEFAULT_CONTRACTS_DIR, outPath: DEFAULT_OUT_PATH });
  console.log(`[codegen-api] done.`);
}

// Run as CLI when invoked directly (not when imported by tests).
const invokedAsScript = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedAsScript) {
  main().catch((err: unknown) => {
    console.error('[codegen-api] failed:', err);
    process.exit(1);
  });
}
