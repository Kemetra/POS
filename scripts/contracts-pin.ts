/**
 * RT-217 — the `contracts/backend-core/PIN` file format and the re-pin argument
 * grammar, shared by `scripts/contracts-repin.ts` and the contract-conformance
 * suite (`tests/contract/backend-core/`). Pure: no I/O.
 *
 * The PIN records which Backend-Core commit the vendored OpenAPI contracts came
 * from and the git blob SHA of every vendored file, so the suite can prove the
 * snapshot is exactly what Backend-Core published at that commit (no hand edits).
 */
import { createHash } from 'node:crypto';

/** Where the vendored contracts live in Backend-Core. */
export const BACKEND_CORE_REPO = 'Kemetra/Backend-Core';
export const BACKEND_CORE_OPENAPI_ROOT = 'packages/contracts/openapi';

export interface PinnedFile {
  /** Path relative to `packages/contracts/openapi/` (and to `contracts/backend-core/openapi/`). */
  readonly path: string;
  /** Git blob SHA-1 of the file's bytes at `commit`. */
  readonly blobSha: string;
}

export interface ContractsPin {
  readonly repo: string;
  readonly commit: string;
  readonly source: string;
  readonly files: readonly PinnedFile[];
}

const HEADER = [
  '# Backend-Core OpenAPI contracts vendored for the POS contract-conformance suite',
  '# (tests/contract/backend-core, RT-217). Generated by `npm run contracts:repin`.',
  '# Do not hand-edit: the suite checks every file below against its git blob SHA.',
];

const SHA1 = /^[0-9a-f]{40}$/;

/** The git blob SHA-1 of `bytes` (what `git hash-object` prints). */
export function gitBlobSha(bytes: Uint8Array): string {
  return createHash('sha1')
    .update(`blob ${String(bytes.byteLength)}\0`)
    .update(bytes)
    .digest('hex');
}

// ─── path safety ─────────────────────────────────────────────────────────────

interface PathRule {
  readonly reason: string;
  readonly broken: (p: string) => boolean;
}

const DOT_SEGMENTS: ReadonlySet<string> = new Set(['', '.', '..']);
const OPENAPI_FILE = /\.(ya?ml|json)$/;

const PATH_RULES: readonly PathRule[] = [
  { reason: 'absolute', broken: (p) => p.startsWith('/') },
  { reason: 'backslash', broken: (p) => p.includes('\\') },
  {
    reason: 'empty, . or .. segment',
    broken: (p) => p.split('/').some((s) => DOT_SEGMENTS.has(s)),
  },
  { reason: 'not .yaml/.yml/.json', broken: (p) => !OPENAPI_FILE.test(p) },
];

/** Reject anything that could escape the vendored directory or is not an OpenAPI file. */
export function assertSafeRelativePath(p: string): void {
  const rule = PATH_RULES.find((r) => r.broken(p));
  if (rule === undefined) return;
  throw new Error(`contracts PIN: unsafe or non-OpenAPI path "${p}" (${rule.reason})`);
}

// ─── PIN format ──────────────────────────────────────────────────────────────

export function formatPin(pin: ContractsPin): string {
  const files = [...pin.files].sort((a, b) => a.path.localeCompare(b.path));
  return [
    ...HEADER,
    `repo: ${pin.repo}`,
    `commit: ${pin.commit}`,
    `source: ${pin.source}`,
    ...files.map((f) => `file: ${f.path} ${f.blobSha}`),
    '',
  ].join('\n');
}

interface PinDraft {
  repo?: string;
  commit?: string;
  source?: string;
  readonly files: PinnedFile[];
}

interface PinField {
  readonly key: string;
  readonly value: string;
}

function parseFileEntry(field: PinField): PinnedFile {
  const parts = field.value.split(/\s+/);
  const [path, blobSha] = parts as [string, string | undefined];
  if (parts.length !== 2 || !SHA1.test(blobSha ?? '')) {
    throw new Error(`contracts PIN: malformed file line "file: ${field.value}"`);
  }
  assertSafeRelativePath(path);
  return { path, blobSha: blobSha as string };
}

const FIELD_READERS: Readonly<Record<string, (draft: PinDraft, field: PinField) => void>> = {
  repo: (draft, field) => {
    draft.repo = field.value;
  },
  commit: (draft, field) => {
    draft.commit = field.value;
  },
  source: (draft, field) => {
    draft.source = field.value;
  },
  file: (draft, field) => {
    draft.files.push(parseFileEntry(field));
  },
};

const PIN_LINE = /^([a-z]+):\s+(\S.*)$/;

/** A `key: value` field, or null for a blank / comment line. */
function parseField(raw: string): PinField | null {
  const line = raw.trim();
  if (line === '' || line.startsWith('#')) return null;
  const match = PIN_LINE.exec(line);
  if (match === null) throw new Error(`contracts PIN: unparseable line "${line}"`);
  return { key: match[1] as string, value: (match[2] as string).trim() };
}

function readField(draft: PinDraft, field: PinField): void {
  const reader = FIELD_READERS[field.key];
  if (reader === undefined) throw new Error(`contracts PIN: unknown key "${field.key}"`);
  reader(draft, field);
}

const PIN_CHECKS: ReadonlyArray<{
  readonly message: string;
  readonly ok: (d: PinDraft) => boolean;
}> = [
  { message: 'repo is required', ok: (d) => d.repo !== undefined },
  { message: 'source is required', ok: (d) => d.source !== undefined },
  { message: 'commit must be a full SHA', ok: (d) => SHA1.test(d.commit ?? '') },
  { message: 'no files pinned', ok: (d) => d.files.length > 0 },
  {
    message: 'duplicate file entry',
    ok: (d) => new Set(d.files.map((f) => f.path)).size === d.files.length,
  },
];

export function parsePin(text: string): ContractsPin {
  const draft: PinDraft = { files: [] };
  for (const raw of text.split(/\r?\n/)) {
    const field = parseField(raw);
    if (field !== null) readField(draft, field);
  }
  const failed = PIN_CHECKS.find((check) => !check.ok(draft));
  if (failed !== undefined) throw new Error(`contracts PIN: ${failed.message}`);
  return {
    repo: draft.repo as string,
    commit: draft.commit as string,
    source: draft.source as string,
    files: draft.files,
  };
}

// ─── re-pin arguments ────────────────────────────────────────────────────────

export interface RepinArgs {
  ref: string;
  readonly add: string[];
  readonly remove: string[];
}

const REPIN_FLAGS: Readonly<Record<string, (args: RepinArgs, value: string) => void>> = {
  '--ref': (args, value) => {
    args.ref = value;
  },
  '--add': (args, value) => {
    args.add.push(value);
  },
  '--remove': (args, value) => {
    args.remove.push(value);
  },
};

interface FlagPair {
  readonly flag: string;
  readonly value: string | undefined;
}

function applyFlag(args: RepinArgs, pair: FlagPair): void {
  const apply = REPIN_FLAGS[pair.flag];
  if (apply === undefined) throw new Error(`unknown argument "${pair.flag}"`);
  const value = pair.value ?? '--';
  if (value.startsWith('--')) throw new Error(`${pair.flag} needs a value`);
  apply(args, value);
}

/** `--ref <ref>` (default `main`), repeatable `--add <path>` / `--remove <path>`. */
export function parseRepinArgs(argv: readonly string[]): RepinArgs {
  const args: RepinArgs = { ref: 'main', add: [], remove: [] };
  for (let i = 0; i < argv.length; i += 2) {
    applyFlag(args, { flag: argv[i] ?? '', value: argv[i + 1] });
  }
  return args;
}

// ─── scheduled re-pin PRs (RT-676) ───────────────────────────────────────────

export interface PinDiff {
  readonly changed: readonly string[];
  readonly added: readonly string[];
  readonly removed: readonly string[];
}

/** Which pinned files differ by blob SHA between two pins. Paths come back sorted. */
export function diffPins(before: ContractsPin, after: ContractsPin): PinDiff {
  const old = new Map(before.files.map((f) => [f.path, f.blobSha]));
  const next = new Map(after.files.map((f) => [f.path, f.blobSha]));
  const sorted = (paths: Iterable<string>): string[] =>
    [...paths].sort((a, b) => a.localeCompare(b));
  return {
    changed: sorted([...next.keys()].filter((p) => old.has(p) && old.get(p) !== next.get(p))),
    added: sorted([...next.keys()].filter((p) => !old.has(p))),
    removed: sorted([...old.keys()].filter((p) => !next.has(p))),
  };
}

export type BranchAction = 'push' | 'comment';

/**
 * The bot may only force-push its branch when it owns every commit on it: a human
 * who added commits to adapt POS code must not be overwritten. `null` is a commit
 * whose author email GitHub could not link to an account, so it counts as human.
 */
export function decideBranchAction(
  commitAuthors: readonly (string | null)[],
  botLogin: string,
): BranchAction {
  return commitAuthors.every((login) => login === botLogin) ? 'push' : 'comment';
}

export interface RepinPrBodyArgs {
  readonly before: ContractsPin;
  readonly after: ContractsPin;
  readonly diff: PinDiff;
  readonly conformance: 'pass' | 'fail';
  readonly failureSummary?: string | undefined;
}

const short = (sha: string): string => sha.slice(0, 7);

function fileSection(title: string, paths: readonly string[]): string[] {
  return paths.length === 0 ? [] : [`**${title}**`, ...paths.map((p) => `- \`${p}\``), ''];
}

function conformanceSection(args: RepinPrBodyArgs): string[] {
  if (args.conformance === 'pass') {
    return ['Conformance (`tests/contract/backend-core`): **pass**.'];
  }
  return [
    'Conformance (`tests/contract/backend-core`): **FAIL**. This PR is a draft labelled',
    '`contracts-break`: POS code must be adapted to the new contract before it can merge.',
    '',
    '```',
    args.failureSummary?.trim() || '(no failure summary captured; see the workflow run)',
    '```',
  ];
}

/** The body of the bot repin PR. Plain markdown; the compare URL names the Backend-Core range. */
export function renderRepinPrBody(args: RepinPrBodyArgs): string {
  const { before, after, diff } = args;
  return [
    `Repins the vendored Backend-Core contracts \`${short(before.commit)}\` -> \`${short(after.commit)}\`.`,
    '',
    `Backend-Core changes: https://github.com/${BACKEND_CORE_REPO}/compare/${before.commit}...${after.commit}`,
    '',
    ...fileSection('Changed contract files', diff.changed),
    ...fileSection('Added contract files', diff.added),
    ...fileSection('Removed contract files', diff.removed),
    ...conformanceSection(args),
    '',
    'Opened by `contracts-repin.yml` (RT-676). If you push commits to this branch the bot',
    'stops force-pushing it and comments here instead.',
    '',
  ].join('\n');
}

// ESC, then `[` (as a one-member class), then colour parameters.
const ANSI_ESCAPE = new RegExp(`${String.fromCodePoint(27)}[[][0-9;]*m`, 'g');
const SUMMARY_MAX_CHARS = 4000;

/** The tail of a test run's output, colour codes stripped, small enough for a PR body. */
export function summarizeTestLog(log: string): string {
  const clean = log.replace(ANSI_ESCAPE, '').trim();
  return clean.length <= SUMMARY_MAX_CHARS ? clean : `...${clean.slice(-SUMMARY_MAX_CHARS)}`;
}

export interface PrState {
  readonly isDraft: boolean;
  readonly labels: readonly string[];
}

export interface PrStatePlan {
  /** Convert to draft. */
  readonly draft: boolean;
  /** Mark ready for review. */
  readonly ready: boolean;
  readonly addLabel: boolean;
  readonly removeLabel: boolean;
}

/**
 * The draft/label changes an existing bot PR needs. A conformance failure drafts it
 * and labels it; a later pass undrafts it only if the bot drafted it (the label marks
 * that). The label is therefore added only when the bot itself converts the PR to
 * draft, so a PR a human chose to keep as a draft stays one.
 */
export function planPrState(pr: PrState, label: string, failed: boolean): PrStatePlan {
  const labelled = pr.labels.includes(label);
  return failed
    ? { draft: !pr.isDraft, ready: false, addLabel: !pr.isDraft && !labelled, removeLabel: false }
    : { draft: false, ready: pr.isDraft && labelled, addLabel: false, removeLabel: labelled };
}
